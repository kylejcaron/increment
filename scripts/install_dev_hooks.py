"""Install project hooks using the pinned, stable user-level prek executable."""

from __future__ import annotations

import argparse
import os
import re
import shlex
import subprocess
import sys
import tomllib
from pathlib import Path


class HookInstallError(RuntimeError):
    """A safe development-hook installation could not be completed."""


def locked_prek_version(lock_path: Path) -> str:
    """Return the unique prek version recorded in ``uv.lock``."""
    try:
        lock = tomllib.loads(lock_path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise HookInstallError(f"cannot read dependency lock {lock_path}: {exc}") from exc

    packages = [package for package in lock.get("package", []) if package.get("name") == "prek"]
    versions = {package.get("version") for package in packages}
    if len(packages) != 1 or len(versions) != 1 or not isinstance(next(iter(versions), None), str):
        raise HookInstallError(
            f"expected exactly one locked prek package in {lock_path}; found {len(packages)}"
        )
    return next(iter(versions))


def _stable_tool_bin() -> Path:
    try:
        result = subprocess.run(
            ["uv", "tool", "dir", "--bin"], check=True, capture_output=True, text=True
        )
    except (OSError, subprocess.CalledProcessError) as exc:
        raise HookInstallError("cannot locate uv's stable user-tool executable directory") from exc
    output = result.stdout.strip()
    if not output:
        raise HookInstallError("uv returned an empty stable user-tool executable directory")
    return Path(output).expanduser().resolve()


def _validate_stable_executable(repo: Path, prek: Path) -> Path:
    tool_bin = _stable_tool_bin()
    executable_path = prek.expanduser().absolute()
    executable_path = executable_path.parent.resolve() / executable_path.name
    try:
        executable_path.relative_to(tool_bin)
    except ValueError as exc:
        raise HookInstallError(
            f"prek must come from uv's stable user-tool directory ({tool_bin}), "
            f"not {executable_path}"
        ) from exc
    executable = executable_path.resolve()
    try:
        executable.relative_to(repo.resolve())
    except ValueError:
        pass
    else:
        raise HookInstallError(f"refusing project-local hook executable: {executable}")
    if any(part in {".venv", ".worktrees"} for part in executable.parts):
        raise HookInstallError(f"refusing project-environment hook executable: {executable}")
    if not executable.is_file() or not os.access(executable, os.X_OK):
        raise HookInstallError(f"prek executable is missing or not executable: {executable_path}")
    return executable_path


def _is_managed_hook(path: Path, executable: Path) -> bool:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeError):
        return False
    if (
        not lines
        or not any(line.startswith("# File generated by prek:") for line in lines)
        or not any(line.startswith("# ID: ") for line in lines)
    ):
        return False
    executable_lines = [line for line in lines if line.startswith("PREK=")]
    if len(executable_lines) != 1:
        return False
    match = re.fullmatch(r'PREK="([^"]+)"', executable_lines[0])
    return match is not None and Path(match.group(1)).resolve() == executable.resolve()


def _is_guarded_pre_push(hook: Path, native: Path, executable: Path) -> bool:
    try:
        first_lines = hook.read_text(encoding="utf-8").splitlines()[:2]
    except (OSError, UnicodeError):
        return False
    return first_lines == ["#!/bin/sh", "# increment-managed-pre-push-v1"] and _is_managed_hook(
        native, executable
    )


def _stable_python(repo: Path) -> Path:
    executable = Path(getattr(sys, "_base_executable", sys.executable)).resolve()
    try:
        executable.relative_to(repo.resolve())
    except ValueError:
        pass
    else:
        raise HookInstallError(f"refusing project-local guard interpreter: {executable}")
    if any(part in {".venv", ".worktrees"} for part in executable.parts):
        raise HookInstallError(f"refusing project-environment guard interpreter: {executable}")
    if not executable.is_file() or not os.access(executable, os.X_OK):
        raise HookInstallError(f"guard interpreter is missing or not executable: {executable}")
    return executable


def _pre_push_wrapper(native: Path, python: Path) -> str:
    native_path = shlex.quote(str(native))
    interpreter = shlex.quote(str(python))
    return (
        "#!/bin/sh\n"
        "# increment-managed-pre-push-v1\n"
        "set -eu\n"
        'input=$(mktemp "${TMPDIR:-/tmp}/increment-pre-push.XXXXXX")\n'
        'cleanup() { rm -f "$input"; }\n'
        "trap cleanup EXIT\n"
        "trap 'exit 129' HUP\n"
        "trap 'exit 130' INT\n"
        "trap 'exit 143' TERM\n"
        'cat > "$input"\n'
        "repo=$(git rev-parse --show-toplevel)\n"
        f'{interpreter} "$repo/scripts/check_push_targets.py" --repo "$repo" < "$input"\n'
        "set +e\n"
        f'{native_path} "$@" < "$input"\n'
        "status=$?\n"
        'exit "$status"\n'
    )


def _install_pre_push_guard(hooks: Path, executable: Path, python: Path) -> None:
    hook = hooks / "pre-push"
    native = hooks / "pre-push.prek"
    if _is_guarded_pre_push(hook, native, executable):
        return
    if not _is_managed_hook(hook, executable):
        raise HookInstallError(f"expected prek-generated pre-push hook at {hook}")
    hook.replace(native)
    hook.write_text(_pre_push_wrapper(native, python), encoding="utf-8")
    hook.chmod(0o755)


def _check_hook_ownership(repo: Path, executable: Path) -> None:
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--git-path", "hooks"],
            cwd=repo,
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError) as exc:
        raise HookInstallError(f"{repo} is not an accessible Git worktree") from exc
    hooks = Path(result.stdout.strip())
    if not hooks.is_absolute():
        hooks = repo / hooks
    hooks = hooks.resolve()
    for hook_type in ("pre-commit", "pre-push"):
        hook = hooks / hook_type
        legacy = hooks / f"{hook_type}.legacy"
        if hook.is_symlink() and not hook.exists():
            raise HookInstallError(f"refusing dangling {hook_type} hook symlink: {hook}")
        guarded_pre_push = _is_guarded_pre_push(
            hooks / "pre-push", hooks / "pre-push.prek", executable
        )
        managed = _is_managed_hook(hook, executable)
        if hook_type == "pre-push" and guarded_pre_push:
            managed = True
        if os.path.lexists(legacy) and not managed:
            raise HookInstallError(
                f"refusing to replace existing {hook_type} or {hook_type}.legacy ownership "
                f"in {hooks}; preserve or resolve those hooks manually"
            )
        if (
            hook_type == "pre-push"
            and os.path.lexists(hooks / "pre-push.prek")
            and not guarded_pre_push
        ):
            raise HookInstallError(
                f"refusing existing native pre-push hook: {hooks / 'pre-push.prek'}"
            )


def install_hooks(repo: Path, *, prek: Path) -> None:
    """Install pre-commit and pre-push shims without replacing existing ownership."""
    repo = repo.expanduser().resolve()
    if not repo.is_dir():
        raise HookInstallError(f"repository directory does not exist: {repo}")
    executable = _validate_stable_executable(repo, prek)
    try:
        version = subprocess.run(
            [str(executable), "--version"], cwd=repo, check=True, capture_output=True, text=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError) as exc:
        raise HookInstallError(f"could not execute stable prek tool {executable}") from exc
    version_match = re.search(r"(?:^|\s)(\d+\.\d+\.\d+)(?:\s|$)", version)
    if version_match is None:
        raise HookInstallError(f"could not determine prek version from {version!r}")
    locked = locked_prek_version(repo / "uv.lock")
    if version_match.group(1) != locked:
        raise HookInstallError(
            f"stable prek version {version_match.group(1)} does not match uv.lock ({locked}); "
            "manage the user-level prek tool explicitly before installing hooks"
        )
    python = _stable_python(repo)
    try:
        _check_hook_ownership(repo, executable)
        hooks_result = subprocess.run(
            ["git", "rev-parse", "--git-path", "hooks"],
            cwd=repo,
            check=True,
            capture_output=True,
            text=True,
        )
        hooks = Path(hooks_result.stdout.strip())
        if not hooks.is_absolute():
            hooks = repo / hooks
        hooks = hooks.resolve()
        install_command = [str(executable), "install", "-t", "pre-commit"]
        if not _is_guarded_pre_push(hooks / "pre-push", hooks / "pre-push.prek", executable):
            install_command.extend(["-t", "pre-push"])
        subprocess.run(install_command, cwd=repo, check=True)
        _install_pre_push_guard(hooks, executable, python)
    except subprocess.CalledProcessError as exc:
        raise HookInstallError(
            f"prek install failed with exit status {exc.returncode}; no overwrite option was used"
        ) from exc
    except OSError as exc:
        raise HookInstallError(f"could not execute stable prek tool {executable}") from exc


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", required=True, type=Path, help="absolute path to the repository")
    args = parser.parse_args(argv)
    if not args.repo.is_absolute():
        parser.error("--repo must be an absolute path")

    try:
        locked = locked_prek_version(args.repo / "uv.lock")
        executable = _stable_tool_bin() / ("prek.exe" if sys.platform == "win32" else "prek")
        if not executable.is_file() or not os.access(executable, os.X_OK):
            raise HookInstallError(
                f"stable prek tool is not installed. Install it explicitly with: "
                f"uv tool install prek=={locked}"
            )
        install_hooks(args.repo, prek=executable)
    except HookInstallError as exc:
        print(f"install-dev-hooks: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
